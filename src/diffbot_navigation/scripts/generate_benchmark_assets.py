def world_to_grid(point, map_config):
    resolution = float(map_config['resolution'])
    origin_x, origin_y, _ = map_config['origin']
    x, y = point[:2]
    return (
        math.floor((x - origin_x) / resolution),
        math.floor((y - origin_y) / resolution),
    )


def validate_connectivity(layout):
    map_config = layout['map']
    resolution = float(map_config['resolution'])
    origin_x, origin_y, _ = map_config['origin']
    width = int(map_config['width'])
    height = int(map_config['height'])
    clearance = float(layout['robot']['validation_clearance'])

    def is_free(cell):
        grid_x, grid_y = cell
        if not (0 <= grid_x < width and 0 <= grid_y < height):
            return False
        x = origin_x + (grid_x + 0.5) * resolution
        y = origin_y + (grid_y + 0.5) * resolution
        return not any(
            obstacle_contains(obstacle, x, y, clearance)
            for obstacle in layout['obstacles']
        )

    start = world_to_grid(layout['robot']['start'], map_config)
    if not is_free(start):
        raise ValueError('robot start is occupied after applying clearance')

    reachable = {start}
    queue = deque([start])
    cardinal = ((1, 0), (-1, 0), (0, 1), (0, -1))
    diagonal = ((1, 1), (1, -1), (-1, 1), (-1, -1))

    while queue:
        current_x, current_y = queue.popleft()
        for delta_x, delta_y in cardinal + diagonal:
            neighbor = (current_x + delta_x, current_y + delta_y)
            if neighbor in reachable or not is_free(neighbor):
                continue
            if delta_x and delta_y:
                side_x = (current_x + delta_x, current_y)
                side_y = (current_x, current_y + delta_y)
                if not is_free(side_x) or not is_free(side_y):
                    continue
            reachable.add(neighbor)
            queue.append(neighbor)

    for goal in layout['goals']:
        goal_cell = world_to_grid(goal['pose'], map_config)
        if not is_free(goal_cell):
            raise ValueError(
                f"goal '{goal['name']}' is occupied after applying clearance"
            )
        if goal_cell not in reachable:
            raise ValueError(f"goal '{goal['name']}' is not reachable")

    return len(layout['goals']), len(reachable)


def compare_or_write(path, content, check_only):
    expected = content.encode('utf-8') if isinstance(content, str) else content
    if check_only:
        if not path.exists() or path.read_bytes() != expected:
            raise ValueError(f'generated asset is stale: {path}')
        return

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(expected)


def main():
    arguments = parse_arguments()
    layout = load_layout(arguments.layout)
    goal_count, reachable_cells = validate_connectivity(layout)

    compare_or_write(WORLD_PATH, render_world(layout), arguments.check)
    compare_or_write(MAP_IMAGE_PATH, render_map(layout), arguments.check)
    compare_or_write(MAP_YAML_PATH, render_map_yaml(layout), arguments.check)

    action = 'verified' if arguments.check else 'generated'
    print(
        f'{action} benchmark assets: {goal_count} goals reachable, '
        f'{reachable_cells} clearance-safe grid cells'
    )


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, yaml.YAMLError) as error:
        print(f'error: {error}', file=sys.stderr)
        sys.exit(1)
